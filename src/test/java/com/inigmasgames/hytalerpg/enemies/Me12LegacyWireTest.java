/** Fixtures captured with the b0844f8a production serializer, before v2 model edits. */
class Me12LegacyWireTest {
    @TempDir Path directory;
    @Test void acceptedLegacySealedRecordsKeepTheirExactPayloadsAndChecksums() throws Exception {
        Path fixtures=Path.of("src/test/resources/enemies/me12-v1-wire");
        assertTrue(Files.isDirectory(fixtures),"Historical bytes must never be regenerated by this test");
        var json=new GsonBuilder().disableHtmlEscaping().create();
        try(var files=Files.walk(fixtures)) {
            for(var file:files.filter(p->p.toString().endsWith(".json")).toList()) {
                var parsed=com.google.gson.JsonParser.parseString(Files.readString(file));if(!parsed.isJsonObject())continue;
                var envelope=parsed.getAsJsonObject();
                if(!envelope.has("payload"))continue;
                var payload=envelope.get("payload");
                assertEquals(envelope.get("checksum").getAsString(),RewardIntent.digest(json.toJson(payload)));
                Class<?> type=switch(fixtures.relativize(file).getName(0).toString()) {
                    case "enemy-birth-roots"->EnemyBirthRoot.class;
                    case "enemy-births"->EnemyBirthPlan.class;
                    case "enemy-descriptors"->EnemyDescriptor.class;
                    case "enemy-packs"->EnemyPackRecord.class;
                    case "contexts"->EncounterContributions.Snapshot.class;
                    case "deaths"->EncounterContributions.DeathPlan.class;
                    default->null;
                };
                if(type!=null)assertEquals(payload,json.toJsonTree(json.fromJson(payload,type)),file.toString());
            }
        }
    }
    @Test void stage2HasAnIndependentExactCompiler() throws Exception {
        assertNotNull(Class.forName("com.inigmasgames.hytalerpg.enemies.Me12Planner"));
    }
    @Test void P01ActualBaselineUniqueAuthoredInheritedDeathQuantityAndRewardIntentBytes() throws Exception {
        var json=new GsonBuilder().disableHtmlEscaping().create();
        var fixtures=com.google.gson.JsonParser.parseString(Files.readString(Path.of("src/test/resources/enemies/me12-v1-wire/legacy-extra-wire.json"))).getAsJsonArray();
        assertEquals(7,fixtures.size());
        for(var element:fixtures){var entry=element.getAsJsonObject();var payload=entry.get("payload");var type=Class.forName(entry.get("type").getAsString());
            var restored=json.fromJson(payload,type);assertEquals(payload,json.toJsonTree(restored));assertEquals(entry.get("checksum").getAsString(),RewardIntent.digest(json.toJson(restored)));}
    }
    @Test void P01ActualBaselineJournalAndCheckpointReplayFromSparseExactBytes() throws Exception {
        Path source=Path.of("src/test/resources/enemies/me12-v1-wire");
        try(var files=Files.walk(source)){
            for(var file:files.filter(Files::isRegularFile).toList()){
                String relative=source.relativize(file).toString();if(relative.startsWith("legacy-")||relative.equals("provenance.json"))continue;
                Path target=directory.resolve(relative.replace(".sparse.json","").replace(".hex.txt",""));Files.createDirectories(target.getParent());
                if(relative.endsWith(".sparse.json")){
                    var sparse=com.google.gson.JsonParser.parseString(Files.readString(file)).getAsJsonObject();byte[] bytes=new byte[sparse.get("length").getAsInt()];
                    var prefix=HexFormat.of().parseHex(sparse.get("prefixHex").getAsString());System.arraycopy(prefix,0,bytes,0,prefix.length);
                    assertEquals(sparse.get("sha256").getAsString(),HexFormat.of().formatHex(java.security.MessageDigest.getInstance("SHA-256").digest(bytes)));Files.write(target,bytes);
                }else if(relative.endsWith(".hex.txt"))Files.write(target,HexFormat.of().parseHex(Files.readString(file)));
                else Files.copy(file,target);
            }
        }
        var json=new GsonBuilder().disableHtmlEscaping().create();Path rootFile;
        try(var paths=Files.walk(directory.resolve("enemy-birth-roots"))){rootFile=paths.filter(Files::isRegularFile).findFirst().orElseThrow();}
        var root=json.fromJson(com.google.gson.JsonParser.parseString(Files.readString(rootFile)).getAsJsonObject().get("payload"),EnemyBirthRoot.class);
        try(var store=FileEncounterStore.durableV2(directory)){
            assertEquals(root,store.enemyBirthRoot(root.world(),root.encounter()).orElseThrow());
            assertEquals(root.originalSpawns().getFirst(),store.load(root.world(),root.originalSpawns().getFirst().enemy()).orElseThrow().spawn());
        }
    }
}
